package io.mcpsearch.starter;

// Spring AI 2.0's @McpTool auto-scanner proved unreliable in practice (the annotation
// scanner beans misbehave, and no tools get registered). The robust path is Spring AI's
// @Tool/@ToolParam annotations plus an explicit MethodToolCallbackProvider bean (declared
// in the app's SearchServerConfig) - MethodToolCallbackProvider scans for @Tool, not
// @McpTool. Once registered as a ToolCallback, the MCP server exposes it identically.
import org.springframework.ai.tool.annotation.Tool;
import org.springframework.ai.tool.annotation.ToolParam;

import io.mcpsearch.core.exception.SearchException;
import io.mcpsearch.core.model.Filter;
import io.mcpsearch.core.model.FusionMode;
import io.mcpsearch.core.model.SearchMode;
import io.mcpsearch.core.model.SearchQuery;
import io.mcpsearch.core.model.SearchResponse;
import io.mcpsearch.core.spi.SearchAdapter;

import java.util.Map;

/**
 * The MCP-facing surface of this whole module: one {@code search} tool,
 * with its JSON schema auto-generated by Spring AI from this method's
 * signature via {@code @Tool}/{@code @ToolParam}.
 * <p>
 * Deliberately exposes a simplified parameter surface - query text, topK,
 * and exact-match filters - rather than the full {@link Filter} operator
 * set ({@code RANGE}, {@code IN}, {@code CONTAINS}, etc). This is what an
 * LLM tool-caller can use reliably without needing to construct nested
 * operator objects; richer filtering remains available to any Java caller
 * using {@link SearchAdapter} directly.
 * <p>
 * Registered as a bean by {@code SearchAutoConfiguration}, not by component
 * scanning - a consuming app doesn't scan this starter's package.
 */
public class SearchToolService {

    private final SearchAdapter searchAdapter;
    private final SearchProperties properties;

    public SearchToolService(SearchAdapter searchAdapter, SearchProperties properties) {
        this.searchAdapter = searchAdapter;
        this.properties = properties;
    }

    @Tool(name = "search", description = "Hybrid full-text and semantic search over the configured datastore.")
    public SearchToolResult search(
            @ToolParam(description = "The search query text") String query,
            @ToolParam(description = "Maximum number of results to return", required = false) Integer topK,
            @ToolParam(description = "Exact-match filters as field/value pairs, e.g. {\"category\": \"electronics\"}", required = false)
            Map<String, Object> filters,
            @ToolParam(description = "Search mode: HYBRID (default, text+semantic), VECTOR (semantic only), "
                    + "or TEXT (keyword only). Case-insensitive; unrecognized values fall back to HYBRID.",
                    required = false)
            String mode
    ) {
        SearchQuery.Builder builder = SearchQuery.builder()
                .text(query)
                .mode(parseSearchMode(mode))
                .fusionMode(parseFusionMode(properties.hybrid().defaultMode()))
                .alpha(properties.hybrid().defaultAlpha())
                .size(topK != null ? topK : properties.hybrid().defaultTopK());

        if (filters != null) {
            filters.forEach((field, value) -> builder.filter(Filter.eq(field, value)));
        }

        try {
            SearchResponse response = searchAdapter.search(builder.build());
            return SearchToolResult.from(response);
        } catch (SearchException e) {
            throw new SearchToolException("Search failed: " + e.getMessage(), e);
        }
    }

    /** Parse the caller's mode string; null/blank/unrecognized -> HYBRID (safe default). */
    private SearchMode parseSearchMode(String value) {
        if (value == null || value.isBlank()) {
            return SearchMode.HYBRID;
        }
        try {
            return SearchMode.valueOf(value.trim().toUpperCase());
        } catch (IllegalArgumentException e) {
            return SearchMode.HYBRID;
        }
    }

    private FusionMode parseFusionMode(String value) {
        try {
            return FusionMode.valueOf(value.toUpperCase());
        } catch (IllegalArgumentException e) {
            return FusionMode.RRF;
        }
    }
}
